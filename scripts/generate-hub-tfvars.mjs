#!/usr/bin/env node
/**
 * Generate terraform/environments/hub.tfvars from platform/sites.yaml + env secrets.
 * Used by GitHub Actions platform-site-provision (never commit the output).
 *
 * Writes two files:
 *   hub.generated.tfvars        — site metadata (no secrets)
 *   hub.generated.secrets.tfvars.json — sensitive hub_proxy_secrets map
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  deprovisionSiteMissingError,
  escapeHcl,
  hubProxySecretForGeneratedTfvars,
  resolveAttachHubApiBinding,
  resolveIncludePagesDevAccessDestinations
} from './lib/hub-tfvars.mjs';
import { loadSitesYaml } from './lib/load-sites-yaml.mjs';
import { parseEmailList } from './lib/email-lists.mjs';
import { parseSiteOwnerEmailsEnv, resolveSiteOwnerEmails } from './lib/site-owner-emails.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sitesYamlPath = join(root, 'platform/sites.yaml');
const tfDir = join(root, 'terraform');
const outputArgIndex = process.argv.indexOf('--output');
const outputPath =
  outputArgIndex >= 0
    ? process.argv[outputArgIndex + 1]
    : join(tfDir, 'environments/hub.generated.tfvars');
const secretsOutputPath = outputPath.replace(/\.tfvars$/, '.secrets.tfvars.json');

const accountId = requiredEnv('CLOUDFLARE_ACCOUNT_ID');
const zoneId = requiredEnv('CLOUDFLARE_ZONE_ID');
const workersSubdomain = requiredEnv('WORKERS_SUBDOMAIN');
const accessTeamDomain = requiredEnv('ACCESS_TEAM_DOMAIN');
const zoneName = process.env.ZONE_NAME?.trim() || 'lovely-home.co.uk';
const customerZoneName = process.env.CUSTOMER_ZONE_NAME?.trim() || 'lovely-hub.com';
const customerZoneId = process.env.CUSTOMER_CLOUDFLARE_ZONE_ID?.trim() || '';
const ownerEmails = splitCsv(process.env.OWNER_EMAILS);
const supportOwnerEmails = splitCsv(process.env.SUPPORT_OWNER_EMAILS);
const sitterEmails = splitCsv(process.env.SITTER_EMAILS);
const operatorEmails = splitCsv(process.env.PLATFORM_OPERATOR_EMAILS);
const platformGithubToken = process.env.PLATFORM_GITHUB_TOKEN?.trim() || '';
const platformCfApiToken = process.env.PLATFORM_CF_API_TOKEN?.trim() || '';
const stripeSecretKey = process.env.STRIPE_SECRET_KEY?.trim() || '';
const stripeWebhookSecret = process.env.STRIPE_WEBHOOK_SECRET?.trim() || '';
const stripePriceId = process.env.STRIPE_PRICE_ID?.trim() || '';
const stripePriceIdYearly = process.env.STRIPE_PRICE_ID_YEARLY?.trim() || '';
const provisionSiteId = process.env.PROVISION_SITE_ID?.trim() || '';
const provisionPhase = process.env.PROVISION_PHASE?.trim() || '';
const deprovisionSiteId = process.env.DEPROVISION_SITE_ID?.trim() || '';

// Customer owner emails come from the platform billing database at provision
// time, so they are never written to platform/sites.yaml in a public repo.
/** @type {Record<string, string[]>} */
let billingOwnerEmails = {};
try {
  billingOwnerEmails = parseSiteOwnerEmailsEnv(process.env.SITE_OWNER_EMAILS_JSON);
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}

/** @type {Record<string, string>} */
let hubProxySecretsEnv = {};
if (process.env.HUB_PROXY_SECRETS_JSON?.trim()) {
  try {
    hubProxySecretsEnv = JSON.parse(process.env.HUB_PROXY_SECRETS_JSON);
  } catch {
    console.error('HUB_PROXY_SECRETS_JSON must be valid JSON.');
    process.exit(1);
  }
}

const registry = loadSitesYaml(sitesYamlPath);
const terraformSiteIds = readTerraformSiteIds();
const hubProxySecretsState = readTerraformHubProxySecrets();
const randomProxySiteIds = readRandomHubProxySiteIds();

/** @type {Record<string, string>} */
const hubProxySecretsOut = {};

/** @type {string[]} */
const lines = [
  '# Generated by scripts/generate-hub-tfvars.mjs — do not commit.',
  '',
  `cloudflare_account_id = "${escapeHcl(accountId)}"`,
  `cloudflare_zone_id    = "${escapeHcl(zoneId)}"`,
  `workers_subdomain     = "${escapeHcl(workersSubdomain)}"`,
  `access_team_domain    = "${escapeHcl(accessTeamDomain)}"`,
  `zone_name             = "${escapeHcl(zoneName)}"`,
  ''
];

if (customerZoneId) {
  lines.push(
    `customer_cloudflare_zone_id = "${escapeHcl(customerZoneId)}"`,
    `customer_zone_name          = "${escapeHcl(customerZoneName)}"`,
    ''
  );
}

lines.push(
  'owner_emails = [',
  ...ownerEmails.map((email) => `  "${escapeHcl(email)}",`),
  ']',
  '',
  'support_owner_emails = [',
  ...supportOwnerEmails.map((email) => `  "${escapeHcl(email)}",`),
  ']',
  '',
  'sitter_emails = [',
  ...sitterEmails.map((email) => `  "${escapeHcl(email)}",`),
  ']',
  '',
  'platform_operator_emails = [',
  ...operatorEmails.map((email) => `  "${escapeHcl(email)}",`),
  ']',
  ''
);

if (platformGithubToken) {
  lines.push(`platform_github_token = "${escapeHcl(platformGithubToken)}"`, '');
}

if (platformCfApiToken) {
  lines.push(`platform_cf_api_token = "${escapeHcl(platformCfApiToken)}"`, '');
}

if (stripeSecretKey) {
  lines.push(`stripe_secret_key = "${escapeHcl(stripeSecretKey)}"`, '');
}

if (stripeWebhookSecret) {
  lines.push(`stripe_webhook_secret = "${escapeHcl(stripeWebhookSecret)}"`, '');
}

if (stripePriceId) {
  lines.push(`stripe_price_id = "${escapeHcl(stripePriceId)}"`, '');
}

if (stripePriceIdYearly) {
  lines.push(`stripe_price_id_yearly = "${escapeHcl(stripePriceIdYearly)}"`, '');
}

const marketingSiteOrigin = process.env.MARKETING_SITE_ORIGIN?.trim() || 'https://lovely-home.co.uk';
lines.push(`marketing_site_origin = "${escapeHcl(marketingSiteOrigin)}"`, '');

const marketingAccessFlag = process.env.MARKETING_SITE_ACCESS_PROTECTED?.trim().toLowerCase() ?? '';
const marketingSiteAccessProtected =
  marketingAccessFlag === 'true' || marketingAccessFlag === '1' || marketingAccessFlag === 'yes'
    ? true
    : marketingAccessFlag === 'false' || marketingAccessFlag === '0' || marketingAccessFlag === 'no'
      ? false
      : false;
lines.push(`marketing_site_access_protected = ${marketingSiteAccessProtected}`, '');

const publicSignupFlag = process.env.PUBLIC_SIGNUP_ENABLED?.trim().toLowerCase() ?? '';
const publicSignupEnabled =
  publicSignupFlag === 'true' || publicSignupFlag === '1' || publicSignupFlag === 'yes'
    ? true
    : publicSignupFlag === 'false' || publicSignupFlag === '0' || publicSignupFlag === 'no'
      ? false
      : Boolean(stripeSecretKey && stripeWebhookSecret && stripePriceId && platformGithubToken);
lines.push(`public_signup_enabled = ${publicSignupEnabled}`, '');

const turnstileSiteKey = process.env.TURNSTILE_SITE_KEY?.trim() ?? '';
const turnstileSecretKey = process.env.TURNSTILE_SECRET_KEY?.trim() ?? '';
if (turnstileSiteKey) {
  lines.push(`turnstile_site_key = "${escapeHcl(turnstileSiteKey)}"`, '');
}
if (turnstileSecretKey) {
  lines.push(`turnstile_secret_key = "${escapeHcl(turnstileSecretKey)}"`, '');
}

lines.push(
  'platform_admin = {',
  '  enabled    = true',
  `  hostname   = "platform.${zoneName}"`,
  '  pages_name = "home-dashboard-platform"',
  '}',
  '',
  'sites = {'
);

/** @type {Set<string>} */
const writtenSiteIds = new Set();

/**
 * @param {string} siteId
 * @param {{ hostname?: string, hub_environment?: string, vanilla?: boolean, attach_hub_api_binding?: boolean, owner_emails?: string[], sitter_emails?: string[] }} meta
 */
function appendSiteBlock(siteId, meta) {
  if (writtenSiteIds.has(siteId)) return;

  const hostname = String(meta.hostname ?? '');
  const hubEnvironment = String(meta.hub_environment ?? siteId);
  const vanilla = meta.vanilla !== false;
  const attach = resolveAttachHubApiBinding(siteId, meta, terraformSiteIds, {
    provisionSiteId,
    provisionPhase
  });
  const includePagesDevAccess = resolveIncludePagesDevAccessDestinations(siteId, meta, terraformSiteIds, {
    provisionSiteId,
    provisionPhase
  });

  let proxySecret;
  try {
    proxySecret = hubProxySecretForGeneratedTfvars(
      siteId,
      terraformSiteIds,
      randomProxySiteIds,
      hubProxySecretsEnv,
      hubProxySecretsState
    );
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }

  if (proxySecret) {
    hubProxySecretsOut[siteId] = proxySecret;
  }

  lines.push(`  ${siteId} = {`);
  lines.push(`    hostname        = "${escapeHcl(hostname)}"`);
  lines.push(`    hub_environment = "${escapeHcl(hubEnvironment)}"`);
  lines.push(`    vanilla         = ${vanilla ? 'true' : 'false'}`);
  lines.push(`    terraform       = true`);
  const siteZone = String(meta.zone_name ?? '').trim();
  if (siteZone && siteZone !== zoneName) {
    lines.push(`    zone_name       = "${escapeHcl(siteZone)}"`);
  }
  lines.push(`    attach_hub_api_binding = ${attach ? 'true' : 'false'}`);
  lines.push(`    include_pages_dev_access_destinations = ${includePagesDevAccess ? 'true' : 'false'}`);
  if (meta.access_enabled === false) {
    lines.push('    access_enabled = false');
  }

  const siteOwnerEmails = resolveSiteOwnerEmails(siteId, meta.owner_emails, billingOwnerEmails);
  const siteSitterEmails = parseEmailList(meta.sitter_emails);

  // Customer hubs no longer inherit the platform-wide owner list, so a hub with
  // neither its own owners nor a support identity would lock everyone out.
  const siteZoneName = String(meta.zone_name ?? '').trim() || hostnameZone(hostname) || zoneName;
  if (
    siteZoneName !== zoneName &&
    meta.access_enabled !== false &&
    siteOwnerEmails.length === 0 &&
    supportOwnerEmails.length === 0
  ) {
    console.error(
      `generate-hub-tfvars: ${siteId} is a customer hub with no owner emails. Set the SUPPORT_OWNER_EMAILS secret, or record the owner in the platform billing database, before applying.`
    );
    process.exit(1);
  }
  if (siteOwnerEmails.length > 0) {
    lines.push('    owner_emails = [');
    for (const email of siteOwnerEmails) {
      lines.push(`      "${escapeHcl(email)}",`);
    }
    lines.push('    ]');
  }
  if (siteSitterEmails.length > 0) {
    lines.push('    sitter_emails = [');
    for (const email of siteSitterEmails) {
      lines.push(`      "${escapeHcl(email)}",`);
    }
    lines.push('    ]');
  }

  lines.push('  }');
  writtenSiteIds.add(siteId);
}

for (const [siteId, meta] of Object.entries(registry)) {
  if (meta.terraform === false) continue;
  appendSiteBlock(siteId, meta);
}

if (deprovisionSiteId && !writtenSiteIds.has(deprovisionSiteId) && terraformSiteIds.has(deprovisionSiteId)) {
  const tfSites = readTerraformSitesOutput();
  const contract = tfSites[deprovisionSiteId];
  if (contract) {
    appendSiteBlock(deprovisionSiteId, {
      hostname: contract.hostname,
      hub_environment: contract.hub_environment,
      vanilla: contract.vanilla,
      owner_emails: contract.owner_emails,
      sitter_emails: contract.sitter_emails
    });
  }
}

const missingDeprovisionSite = deprovisionSiteMissingError(deprovisionSiteId, writtenSiteIds);
if (missingDeprovisionSite) {
  console.error(missingDeprovisionSite);
  process.exit(1);
}

lines.push('}', '');

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, lines.join('\n'));
writeFileSync(secretsOutputPath, `${JSON.stringify({ hub_proxy_secrets: hubProxySecretsOut }, null, 2)}\n`);
console.log(`Wrote ${outputPath} and ${secretsOutputPath} (${Object.keys(registry).length} registry sites)`);

/**
 * @param {string} name
 */
function requiredEnv(name) {
  const value = process.env[name]?.trim();
  if (!value) {
    console.error(`Missing required env: ${name}`);
    process.exit(1);
  }
  return value;
}

/**
 * Registry zone for a hostname, e.g. smith.lovely-hub.com → lovely-hub.com.
 *
 * @param {string} hostname
 */
function hostnameZone(hostname) {
  const parts = String(hostname ?? '').trim().toLowerCase().split('.');
  return parts.length > 2 ? parts.slice(1).join('.') : parts.join('.');
}

/**
 * @param {string | undefined} value
 */
function splitCsv(value) {
  if (!value?.trim()) return [];
  return value
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean);
}

/**
 * @returns {Record<string, object>}
 */
function readTerraformSitesOutput() {
  try {
    const raw = execFileSync('terraform', ['output', '-json', 'sites'], {
      cwd: tfDir,
      encoding: 'utf8'
    });
    return JSON.parse(raw);
  } catch {
    return {};
  }
}

/**
 * @returns {Set<string>}
 */
function readTerraformSiteIds() {
  try {
    const raw = execFileSync('terraform', ['output', '-json', 'sites'], {
      cwd: tfDir,
      encoding: 'utf8'
    });
    return new Set(Object.keys(JSON.parse(raw)));
  } catch {
    return new Set();
  }
}

/**
 * @returns {Record<string, string>}
 */
function readTerraformHubProxySecrets() {
  try {
    const raw = execFileSync('terraform', ['output', '-json', 'hub_proxy_secrets'], {
      cwd: tfDir,
      encoding: 'utf8'
    });
    return JSON.parse(raw);
  } catch {
    return {};
  }
}

/**
 * Sites whose hub_proxy_secret is still managed by random_password in state.
 * @returns {Set<string>}
 */
function readRandomHubProxySiteIds() {
  try {
    const raw = execFileSync('terraform', ['state', 'list'], {
      cwd: tfDir,
      encoding: 'utf8'
    });
    /** @type {Set<string>} */
    const ids = new Set();
    for (const line of raw.split('\n')) {
      const match = line.match(/^module\.hub_site\["([^"]+)"\]\.random_password\.hub_proxy\[0\]$/);
      if (match) ids.add(match[1]);
    }
    return ids;
  } catch {
    return new Set();
  }
}
